async function seedAptitudeQuestions() {
  try {
    for (const q of initialAptitudeQuestions) {
      await AptitudeQuestion.findOneAndUpdate(
        { question: q.question },
        q,
        { upsert: true, new: true, setDefaultsOnInsert: true }
      );
    }
    console.log(`[Seed] Seeded ${initialAptitudeQuestions.length} aptitude questions successfully.`);
  } catch (err) {
    console.error('[Seed] Error seeding aptitude questions:', err.message);
  }
}

